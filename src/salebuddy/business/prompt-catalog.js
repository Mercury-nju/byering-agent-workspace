export function resolveBusinessPrompt(text = "") {
  const value = String(text || "");
  if (/候选人|招聘|面试|简历|岗位|入职|Offer/i.test(value)) return COMMON.recruiting;
  if (/学员|课程|试听|招生|报名|培训|续课/i.test(value)) return COMMON.education;
  if (/续费|客户成功|健康度|使用情况|工单|满意度|流失客户/i.test(value)) return COMMON.customerSuccess;
  if (/报价|合同|提案|咨询项目|交付周期|方案初稿|专业服务/i.test(value)) return COMMON.professional;
  if (/线索|潜客|获客|买车|购车|车型|到店|留电话|CRM|跟进|触达|商机|成交/i.test(value)) return COMMON.sales;
  return COMMON.sales;
}

